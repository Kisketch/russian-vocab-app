def gender(pos):
    if pos == '名词·阳性': return '阳性'
    if pos == '名词·阴性': return '阴性'
    if pos == '名词·中性': return '中性'
    if pos == '名词·复数': return '复数'
    return ''

def example(ru, pos, zh):
    if pos.startswith('动词'):
        return 'Я хочу ' + ru + '.', '我想' + zh + '。'
    if pos == '形容词':
        return 'Это ' + ru + ' человек.', '这是一个' + zh + '的人。'
    return 'Это ' + ru + '.', '这是' + zh + '。'

def main():
    unit_lines = open(UNITS, encoding='utf-8').read().splitlines()
    vocab_lines = open(VOCAB, encoding='utf-8').read().splitlines()
    existing_units = set()
    out_units = []
    for line in unit_lines:
        if not line.strip(): continue
        p = line.split('|')
        existing_units.add(p[0])
        if len(p) == 5: line = line + '|1'
        out_units.append(line)
    existing_words = set()
    out_vocab = []
    for line in vocab_lines:
        if not line.strip() or line.startswith('#'): continue
        out_vocab.append(line)
        p = line.split('|')
        if len(p) > 1: existing_words.add(p[1].lower())
    added_units = 0
    added_words = 0
    skipped = []
    for line in DATA.strip().splitlines():
        p = line.split('|')
        if len(p) < 6: continue
        book, no, ru_title, zh_title, desc, worddata = p[:6]
        uid = 'b%su%02d' % (book, int(no))
        if uid not in existing_units:
            out_units.append('%s|%s|%s|%s|%s|%s' % (uid, no, ru_title, zh_title, desc, book))
            existing_units.add(uid)
            added_units += 1
        for token in worddata.split(';'):
            parts = token.split('~')
            if len(parts) != 3: continue
            ru, pos, zh = parts
            if ru.lower() in existing_words:
                skipped.append(ru); continue
            ex_ru, ex_zh = example(ru, pos, zh)
            out_vocab.append('%s|%s|%s|%s|%s|%s|generic' % (uid, ru, pos, zh, ex_ru, ex_zh))
            existing_words.add(ru.lower())
            added_words += 1
    open(UNITS, 'w', encoding='utf-8').write('\n'.join(out_units) + '\n')
    open(VOCAB, 'w', encoding='utf-8').write('\n'.join(out_vocab) + '\n')
    print('units_added=%d words_added=%d skipped=%d' % (added_units, added_words, len(skipped)))
    if skipped: print('skipped:', ', '.join(skipped))

if __name__ == '__main__':
    main()
