lines = open(V, encoding="utf-8").read().splitlines()
have = set(p[1].lower() for p in (l.split("|") for l in lines if l.strip()) if len(p) > 1)
n = 0
for uid, ws in ADD.items():
    for ru, pos, zh in ws:
        if ru.lower() in have: continue
        ex_ru = "Это " + ru + "."; ex_zh = "这是" + zh + "。"
        lines.append("%s|%s|%s|%s|%s|%s|generic" % (uid, ru, pos, zh, ex_ru, ex_zh))
        have.add(ru.lower()); n += 1
open(V, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print("added", n)
