# ---------------------------------------------------------------- 工具
def stem(word, ending):
    assert word.endswith(ending), word
    return word[: -len(ending)]


def soft_endings(stem_):
    """词干以 ж/ш/ч/щ/ц/г+?/к+?/х+? 结尾时，某些词尾用软形式"""
    if not stem_:
        return False
    return stem_[-1] in "жшчщй"


def ы_to_и(stem_):
    """词干末尾是 г/к/х 或 ж/ш/ч/щ/ц 时，接 ы 要变成 и"""
    if not stem_:
        return False
    return stem_[-1] in "гкхжшчщц"


def apply_end(stem_, ending):
    """在词干后接词尾，处理 ы→и 与软词干"""
    if not ending:
        return stem_
    first = ending[0]
    if first in "ыи" and ы_to_и(stem_):
        return stem_ + "и" + ending[1:]
    if first in "еёюя" and soft_endings(stem_):
        # ж/ш/ч/щ/й 后 е→е（不变），但重音 ё 通常写成 ё；这里保持原样
        return stem_ + ending
    return stem_ + ending


# ---------------------------------------------------------------- 名词
def decline_invariable(w):
    """外来不变格名词（метро, такси…）：各格同形"""
    same = {c: w for c in CASES}
    return {"type": "noun-invariable", "sg": same, "pl": same,
            "note": "外来词，不变格（各格同形）"}


def decline_plural_noun(w):
    """只有复数形式的名词（родители, фрукты, дети…）：给出复数各格，单数标注「—」"""
    if w in IRREGULAR_GEN_PL:
        gen = IRREGULAR_GEN_PL[w]
    elif w.endswith("и"):
        stem = w[:-1]
        gen = stem + "ей"
        if w.endswith("ги") or w.endswith("ки") or w.endswith("хи"):
            gen = stem + "ов" if False else stem + "ов"
    else:
        stem = w[:-1]
        gen = stem + "ов"
    soft = w.endswith("и")
    stem = w[:-1]
    pl = {
        "nom": w,
        "gen": gen,
        "dat": stem + ("ям" if soft else "ам"),
        "acc": w,
        "ins": stem + ("ями" if soft else "ами"),
        "prep": stem + ("ях" if soft else "ах"),
    }
    if w in ANIMATE:
        pl["acc"] = gen
    if w in IRREGULAR_PLURAL:
        pl["nom"] = IRREGULAR_PLURAL[w]
    sg = {c: "—" for c in CASES}
    return {"type": "noun-pl", "sg": sg, "pl": pl}


def decline_noun(word, gender, animate):
    w = word.lower()
    sg, pl = {}, {}
    if w in IRREGULAR_PLURAL:
        pl_nom = IRREGULAR_PLURAL[w]
    else:
        pl_nom = None

    # ---- 第一变格法：-а / -я（阴性，及 папа/дядя 等阳性）
    if w.endswith(("а", "я")):
        soft = w.endswith("я")
        s = stem(w, "я" if soft else "а")
        if soft:
            sg = {"nom": w, "gen": s + "и", "dat": apply_end(s, "е"),
                  "acc": s + "ю", "ins": apply_end(s, "ей"), "prep": apply_end(s, "е")}
        else:
            sg = {"nom": w, "gen": apply_end(s, "ы"), "dat": apply_end(s, "е"),
                  "acc": s + "у", "ins": apply_end(s, "ой"), "prep": apply_end(s, "е")}
        # 复数
        if soft:
            base = {"nom": apply_end(s, "и"), "gen": s + "ь" if False else apply_end(s, "ей") if soft_endings(s) else s,
                    "dat": apply_end(s, "ям"), "ins": apply_end(s, "ями"), "prep": apply_end(s, "ях")}
        else:
            gen_pl = (s + "ей") if (soft_endings(s) or s.endswith("й")) else s
            base = {"nom": apply_end(s, "ы"), "gen": gen_pl,
                    "dat": apply_end(s, "ам"), "ins": apply_end(s, "ами"), "prep": apply_end(s, "ах")}
        if pl_nom:
            base["nom"] = pl_nom
        base["acc"] = IRREGULAR_GEN_PL.get(w, base["gen"]) if animate else base["nom"]
        return {"type": "noun1", "sg": sg, "pl": base}

    # ---- 第三变格法：阴性 -ь
    if w.endswith("ь") and gender == "f":
        s = stem(w, "ь")
        sg = {"nom": w, "gen": apply_end(s, "и"), "dat": apply_end(s, "и"),
              "acc": w, "ins": s + "ью", "prep": apply_end(s, "и")}
        base = {"nom": apply_end(s, "и"), "gen": apply_end(s, "ей"),
                "dat": apply_end(s, "ям"), "ins": apply_end(s, "ями"), "prep": apply_end(s, "ях")}
        base["acc"] = base["gen"] if animate else base["nom"]
        return {"type": "noun3", "sg": sg, "pl": base}

    # ---- 第二变格法：阳性/通性 与 中性
    if w.endswith(("о", "е", "ё")) or gender == "n" and not w.endswith(("а", "я", "ь")):
        soft = w.endswith(("е", "ё"))
        if w.endswith("о"):
            s = stem(w, "о")
            sg = {"nom": w, "gen": apply_end(s, "а"), "dat": apply_end(s, "у"),
                  "acc": w, "ins": apply_end(s, "ом"), "prep": apply_end(s, "е")}
            pl = {"nom": s + "а", "gen": s, "dat": apply_end(s, "ам"),
                  "ins": apply_end(s, "ами"), "prep": apply_end(s, "ах")}
        elif w.endswith(("е", "ё")):
            s = stem(w, "ё" if w.endswith("ё") else "е")
            sg = {"nom": w, "gen": apply_end(s, "я"), "dat": apply_end(s, "ю"),
                  "acc": w, "ins": apply_end(s, "ем"), "prep": apply_end(s, "е")}
            pl = {"nom": s + "я", "gen": s, "dat": apply_end(s, "ям"),
                  "ins": apply_end(s, "ями"), "prep": apply_end(s, "ях")}
        else:  # 不应到达
            return {"type": "noun2", "sg": {}, "pl": {}}
        if pl_nom:
            pl["nom"] = pl_nom
        if w in IRREGULAR_GEN_PL:
            pl["gen"] = IRREGULAR_GEN_PL[w]
        pl["acc"] = IRREGULAR_GEN_PL.get(w, pl["gen"]) if animate else pl["nom"]
        return {"type": "noun2n", "sg": sg, "pl": pl}

    if w.endswith(("й", "ий")) or gender == "m" and w.endswith(("й", "ь")) or gender == "m":
        # 阳性：硬辅音 / -й / -ь
        if w.endswith("й"):
            s = stem(w, "й")
            sg = {"nom": w, "gen": apply_end(s, "я"), "dat": apply_end(s, "ю"),
                  "acc": s + "я", "ins": apply_end(s, "ем"), "prep": apply_end(s, "е")}
            pl = {"nom": apply_end(s, "и"), "gen": apply_end(s, "ев") if soft_endings(s) or s.endswith("й") else apply_end(s, "ей"),
                  "dat": apply_end(s, "ям"), "ins": apply_end(s, "ями"), "prep": apply_end(s, "ях")}
        elif w.endswith("ь"):
            s = stem(w, "ь")
            sg = {"nom": w, "gen": apply_end(s, "я"), "dat": apply_end(s, "ю"),
                  "acc": s + "я", "ins": apply_end(s, "ем"), "prep": apply_end(s, "е")}
            pl = {"nom": apply_end(s, "и"), "gen": apply_end(s, "ей"),
                  "dat": apply_end(s, "ям"), "ins": apply_end(s, "ями"), "prep": apply_end(s, "ях")}
        else:  # 硬辅音结尾
            s = w
            sg = {"nom": w, "gen": apply_end(s, "а"), "dat": apply_end(s, "у"),
                  "acc": s + "а", "ins": apply_end(s, "ом"), "prep": apply_end(s, "е")}
            pl = {"nom": apply_end(s, "ы"), "gen": apply_end(s, "ов") if s.endswith(("ж", "ш", "щ", "ч")) else s,
                  "dat": apply_end(s, "ам"), "ins": apply_end(s, "ами"), "prep": apply_end(s, "ах")}
        if pl_nom:
            pl["nom"] = pl_nom
        if w in IRREGULAR_GEN_PL:
            pl["gen"] = IRREGULAR_GEN_PL[w]
        pl["acc"] = IRREGULAR_GEN_PL.get(w, pl["gen"]) if animate else pl["nom"]
        # 阳性四格单数：动物性同二格
        sg["acc"] = sg["gen"] if animate else sg["nom"]
        return {"type": "noun2m", "sg": sg, "pl": pl}

    return {"type": "noun?", "sg": {}, "pl": {}}


