def _verb_stem(w):
    """按不定式词尾切词干：-ить→去「ить」；-ава→去「ва」；-ева→去「ева」；其余去「ть」"""
    if w.endswith("ить"):
        return w[:-3]
    stem = w[:-2] if w.endswith("ть") else w
    if stem.endswith("ава"):
        return stem[:-2]     # встава → вста
    if stem.endswith("ева"):
        return stem[:-3]     # танцева → танц
    return stem


def _eva_verb(w):
    stem = w[:-2] if w.endswith("ть") else w
    return stem.endswith("ева")


def conjugate_verb(inf):
    w = inf.lower()
    if w in IRREGULAR_VERBS:
        forms = IRREGULAR_VERBS[w]
        return {"type": "verb", "present": dict(zip(
            ["1sg", "2sg", "3sg", "1pl", "2pl", "3pl"], forms)), "irregular": True}
    second = (w in SECOND_CONJ_EXC) or w.endswith("ить")
    stem = _verb_stem(w)
    if _eva_verb(w):                      # танцевать → танц+ую/-уют
        endings = ("ую", "уешь", "ует", "уем", "уете", "уют")
    elif second:
        if stem and (stem[-1] in "жшчщй"):
            endings = ("у", "ишь", "ит", "им", "ите", "ат")
        elif stem and (stem[-1] in "бвпфм"):
            endings = ("лю", "ишь", "ит", "им", "ите", "ят")
        else:
            endings = ("ю", "ишь", "ит", "им", "ите", "ят")
    else:
        if stem and (stem[-1] in VOWELS):
            endings = ("ю", "ешь", "ет", "ем", "ете", "ют")   # работать → работают
        else:
            endings = ("у", "ешь", "ет", "ем", "ете", "ут")
    forms = [apply_end(stem, e) for e in endings]
    return {"type": "verb", "present": dict(zip(["1sg", "2sg", "3sg", "1pl", "2pl", "3pl"], forms)),
            "conj": 2 if second else 1}


def past_tense(inf):
    w = inf.lower()
    if w in IRREGULAR_PAST:
        base = IRREGULAR_PAST[w]
        return {"m": base, "f": base + "а", "n": base + "о", "pl": base + "и"}
    if w.endswith("ить"):
        base = w[:-3] + "ил"          # любить → любил
    elif w.endswith("еть"):
        stem = w[:-3]                 # 去掉 еть：смотреть → смотр, болеть → бол
        base = stem + ("ел" if stem and stem[-1] not in VOWELS else "л")
    elif _eva_verb(w):
        base = w[:-2] + "л"           # танцевать → танцевал
    else:
        base = (w[:-2] if w.endswith("ть") else w) + "л"
    return {"m": base, "f": base + "а", "n": base + "о", "pl": base + "и"}


