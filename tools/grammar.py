def decline_adjective(word):
    w = word.lower()
    soft = w.endswith(("ий", "е", "ё")) or w.endswith("ий")
    if w.endswith("ый") or w.endswith("ий"):
        s = stem(w, "ый" if w.endswith("ый") else "ий")
        if w.endswith("ий"):
            forms = {"m": w, "f": apply_end(s, "яя"), "n": apply_end(s, "ее"),
                     "pl": apply_end(s, "ие")}
            oblique = {"gen": apply_end(s, "его"), "dat": apply_end(s, "ему"),
                       "ins": apply_end(s, "им"), "prep": apply_end(s, "ем")}
            short = s + ("ень" if s.endswith(("ж", "ш", "ч", "щ", "щ")) else "ен")
        else:
            forms = {"m": w, "f": s + "ая", "n": s + "ое", "pl": s + "ые"}
            oblique = {"gen": s + "ого", "dat": s + "ому", "ins": s + "ым", "prep": s + "ом"}
            short = s + "ен"
        return {"type": "adj", "forms": forms, "oblique": oblique, "short": short}
    return {"type": "adj?"}


def comparative(word):
    w = word.lower()
    if w.endswith(("ый", "ий")):
        s = stem(w, "ый" if w.endswith("ый") else "ий")
        if w.endswith("кий") or w.endswith("гий") or w.endswith("хий"):
            return {"more": "более " + w, "simple": apply_end(s, "е") if False else s + "е"}
        if s.endswith(("к", "г", "х")):
            return {"more": "более " + w, "simple": s + "е"}
        return {"more": "более " + w, "simple": s + "ее"}
    return {"more": "более " + w, "simple": None}


