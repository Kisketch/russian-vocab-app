def imperative(inf):
    w = inf.lower()
    if w in IRREGULAR_IMPERATIVE:
        return IRREGULAR_IMPERATIVE[w]
    if w.endswith("ить"):
        return apply_end(w[:-3], "и")          # звонить → звони, купить → купи
    if _eva_verb(w):
        return w[:-5] + "уй"                   # танцевать → танцуй
    stem = w[:-2] if w.endswith("ть") else w
    if stem and (stem[-1] in VOWELS):
        return stem + "й"                      # работать → работай
    # 辅音词干：从不规则表现在时第一人称推导（ждать→жду 已列例外）
    if w in IRREGULAR_VERBS:
        one = IRREGULAR_VERBS[w][0]
        st = one[:-2] if one.endswith("лю") else (one[:-1] if one.endswith(("ю", "у")) else stem)
        return st + "и" if st and st[-1] not in VOWELS else st + "й"
    return stem + "ь"


